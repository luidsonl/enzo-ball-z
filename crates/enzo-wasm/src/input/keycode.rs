pub fn supported_key_index(name: &str) -> Option<u8> {
    SUPPORTED_KEYS
        .iter()
        .position(|(n, _)| *n == name)
        .map(|i| i as u8)
}

pub fn supported_key_by_index(index: u8) -> Option<(&'static str, &'static str)> {
    SUPPORTED_KEYS.get(index as usize).copied()
}
