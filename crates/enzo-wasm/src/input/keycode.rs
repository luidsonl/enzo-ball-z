/// Canonical name for persistence/UI: prefer `key_to_name`, fallback to Debug.
pub fn key_canonical_name(key: KeyCode) -> String {
    key_to_name(key)
        .map(|s| s.to_owned())
        .unwrap_or_else(|| format!("{key:?}"))
}

